    print("In particular, the numerator must be divisible by X.")
    print("The numerator is:")
    print("  Num = X * [ (-c*Y^3 + Y^2)*X^2 + (-3*c*Y^2 + 3*Y)*X + (-3*c*Y + 2) ] - c")
