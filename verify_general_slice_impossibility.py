    print("\nRecall that on S = c, using u = Y + 1/X:")
    print("  P(X, Y) = -c * u^3 + u^2 + u/X")
    print("Substituting u = Y + 1/X:")
    print("  P(X, Y) = -c*(Y + 1/X)^3 + (Y + 1/X)^2 + (Y + 1/X)/X")
    print("          = -c*(Y^3 + 3*Y^2/X + 3*Y/X^2 + 1/X^3) + (Y^2 + 2*Y/X + 1/X^2) + Y/X + 1/X^2")
