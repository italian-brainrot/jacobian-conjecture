    print("In particular, it must be divisible by X.")
    print("But: Y^2 * X^2 + 3*Y*X + 2 = X * (Y^2 * X + 3*Y) + 2")
    print("For this to be divisible by X, the remainder 2 must be divisible by X in C[s, t].")
